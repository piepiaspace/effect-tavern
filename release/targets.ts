// The release's one table: every binary it publishes, the Bun target that compiles it, and the runner that builds
// it. The release workflow reads it (`matrix`) and builds every row at once (`compile <asset>`), each binary stamped
// with its own asset name so `tavern update` asks for the build it is; `brew` writes the formula. install.sh and
// install.ps1 pick among the same names by what the machine can run; test/release.ts holds them together.
import { join } from "node:path"

export interface Target {
  /** The release asset, published as `<asset>.gz`; also the binary's own name for itself (TAVERN_ASSET). */
  asset: string
  /** `bun build --compile --target`. */
  bun: string
  /** process.platform of the machine it runs on. */
  os: "android" | "linux" | "darwin" | "win32"
}

export const TARGETS: readonly Target[] = [
  // the name the first phone releases asked for, kept so they update in place
  { asset: "tavern-android", bun: "bun-linux-arm64-android", os: "android" },
  { asset: "tavern-linux-arm64", bun: "bun-linux-arm64", os: "linux" },
  { asset: "tavern-linux-x64", bun: "bun-linux-x64-baseline", os: "linux" },
  { asset: "tavern-linux-arm64-musl", bun: "bun-linux-arm64-musl", os: "linux" },
  { asset: "tavern-linux-x64-musl", bun: "bun-linux-x64-musl", os: "linux" },
  { asset: "tavern-darwin-arm64", bun: "bun-darwin-arm64", os: "darwin" },
  { asset: "tavern-darwin-x64", bun: "bun-darwin-x64", os: "darwin" },
  { asset: "tavern-windows-arm64.exe", bun: "bun-windows-arm64", os: "win32" },
  { asset: "tavern-windows-x64.exe", bun: "bun-windows-x64-baseline", os: "win32" },
]

/** Mach-O binaries build on macOS: Bun's appended program breaks their signature, and only codesign mends it.
 * Blacksmith's macs are all Apple Silicon: the x64 one is signed there and checked under Rosetta. */
const runner = (t: Target) => (t.os === "darwin" ? "blacksmith-6vcpu-macos-latest" : "blacksmith-4vcpu-ubuntu-2604")

const root = join(import.meta.dir, "..")
const dist = join(root, "packages/server/dist")
const sha256 = async (file: string) => Bun.CryptoHasher.hash("sha256", await Bun.file(file).bytes(), "hex")

/** One target into packages/server/dist/<asset>, and <asset>.gz beside it. VERSION from the environment. */
const compile = async (t: Target) => {
  const r = Bun.spawnSync(["bun", "run", "compile"], {
    cwd: join(root, "packages/server"),
    env: { ...Bun.env, TARGET: t.bun, ASSET: t.asset },
    stdout: "inherit",
    stderr: "inherit",
  })
  if (r.exitCode !== 0) throw new Error(`compile ${t.asset}: exit ${r.exitCode}`)
  if (t.os === "darwin" && process.platform === "darwin") {
    const s = Bun.spawnSync(["codesign", "--force", "--sign", "-", join(dist, t.asset)], { stderr: "inherit" })
    if (s.exitCode !== 0) throw new Error(`codesign ${t.asset}: exit ${s.exitCode}`)
  }
  await Bun.write(join(dist, `${t.asset}.gz`), Bun.gzipSync(await Bun.file(join(dist, t.asset)).bytes(), { level: 9 }))
}

/** The Homebrew formula for a tag, its four binaries pinned by the sums of the .gz files in `dir`. */
export const brew = async (tag: string, dir: string) => {
  const url = (asset: string) => `https://github.com/piepiaspace/effect-tavern/releases/download/${tag}/${asset}.gz`
  const pin = async (asset: string) =>
    `      url "${url(asset)}"\n      sha256 "${await sha256(join(dir, `${asset}.gz`))}"`
  // Homebrew's block names, then the assets'
  const both = async (block: string, os: string) => `  on_${block} do
    on_arm do
${await pin(`tavern-${os}-arm64`)}
    end
    on_intel do
${await pin(`tavern-${os}-x64`)}
    end
  end`
  return `# Generated by release/targets.ts for ${tag}; do not edit.
class Tavern < Formula
  desc "Effect Tavern: the tavern command"
  homepage "https://github.com/piepiaspace/effect-tavern"
  version "${tag.replace(/^v/, "")}"

${await both("macos", "darwin")}
${await both("linux", "linux")}

  def install
    # Homebrew unpacks the .gz to the one file it held
    bin.install Dir["*tavern-*"].first => "tavern"
    chmod 0755, bin/"tavern"
  end

  test do
    assert_equal "tavern #{version}", shell_output("#{bin}/tavern --version").strip
  end
end
`
}

if (import.meta.main) {
  const [command, a, b] = Bun.argv.slice(2)
  const target = TARGETS.find((t) => t.asset === a)
  if (command === "matrix")
    process.stdout.write(JSON.stringify({ include: TARGETS.map((t) => ({ asset: t.asset, runner: runner(t) })) }))
  else if (command === "compile" && target) await compile(target)
  else if (command === "brew" && a && b) process.stdout.write(await brew(a, b))
  else {
    console.error("usage: bun release/targets.ts matrix | compile <asset> | brew <tag> <dir of .gz>")
    process.exit(2)
  }
}
