// The release's one table: every binary it publishes and the Bun target that compiles it. `bun release/targets.ts
// compile` builds them (each stamped with its own asset name, so `tavern update` asks for the build it is), `brew` the
// formula. install.sh and install.ps1 pick among the same names by what the machine can run; test/release.ts holds
// them together.
import { createHash } from "node:crypto"
import { readFileSync, writeFileSync } from "node:fs"
import { join } from "node:path"
import { gzipSync } from "node:zlib"

export interface Target {
  /** The release asset, published as `<asset>.gz`; also the binary's own name for itself (TAVERN_ASSET). */
  asset: string
  /** `bun build --compile --target`. */
  bun: string
  /** process.platform of the machine it runs on. */
  os: "android" | "linux" | "darwin" | "win32"
}

export const TARGETS: readonly Target[] = [
  // the name the first phone releases asked for, kept so they update in place
  { asset: "tavern-android", bun: "bun-linux-arm64-android", os: "android" },
  { asset: "tavern-linux-arm64", bun: "bun-linux-arm64", os: "linux" },
  { asset: "tavern-linux-x64", bun: "bun-linux-x64-baseline", os: "linux" },
  { asset: "tavern-linux-arm64-musl", bun: "bun-linux-arm64-musl", os: "linux" },
  { asset: "tavern-linux-x64-musl", bun: "bun-linux-x64-musl", os: "linux" },
  { asset: "tavern-darwin-arm64", bun: "bun-darwin-arm64", os: "darwin" },
  { asset: "tavern-darwin-x64", bun: "bun-darwin-x64", os: "darwin" },
  { asset: "tavern-windows-arm64.exe", bun: "bun-windows-arm64", os: "win32" },
  { asset: "tavern-windows-x64.exe", bun: "bun-windows-x64-baseline", os: "win32" },
]

const root = join(import.meta.dir, "..")
const dist = join(root, "packages/server/dist")
const sha256 = (file: string) => createHash("sha256").update(readFileSync(file)).digest("hex")

/** Every target into packages/server/dist/<asset>, and <asset>.gz beside it. VERSION from the environment. */
const compile = () => {
  for (const t of TARGETS) {
    const r = Bun.spawnSync(["bun", "run", "compile"], {
      cwd: join(root, "packages/server"),
      env: { ...process.env, TARGET: t.bun, ASSET: t.asset },
      stdout: "inherit",
      stderr: "inherit",
    })
    if (r.exitCode !== 0) throw new Error(`compile ${t.asset}: exit ${r.exitCode}`)
    // a Mach-O built off its own machine keeps Bun's signature, which the appended program breaks: sign it again
    if (t.os === "darwin" && process.platform === "darwin")
      Bun.spawnSync(["codesign", "--force", "--sign", "-", join(dist, t.asset)], {
        stdout: "inherit",
        stderr: "inherit",
      })
    writeFileSync(join(dist, `${t.asset}.gz`), gzipSync(readFileSync(join(dist, t.asset)), { level: 9 }))
  }
}

/** The Homebrew formula for a tag, its four binaries pinned by the sums of the .gz files in dist. */
const brew = (tag: string) => {
  const url = (asset: string) => `https://github.com/waylon256yhw/effect-tavern/releases/download/${tag}/${asset}.gz`
  const pin = (asset: string, pad: string) =>
    `${pad}url "${url(asset)}"\n${pad}sha256 "${sha256(join(dist, `${asset}.gz`))}"`
  const both = (os: string) => `  on_${os} do
    on_arm do
${pin(`tavern-${os}-arm64`, "      ")}
    end
    on_intel do
${pin(`tavern-${os}-x64`, "      ")}
    end
  end`
  return `# Generated by release/targets.ts for ${tag}; do not edit.
class Tavern < Formula
  desc "Effect Tavern: the tavern command"
  homepage "https://github.com/waylon256yhw/effect-tavern"
  version "${tag.replace(/^v/, "")}"

${both("macos").replace(/tavern-macos/g, "tavern-darwin")}
${both("linux")}

  def install
    # Homebrew unpacks the .gz to the one file it held
    bin.install Dir["*tavern-*"].first => "tavern"
    chmod 0755, bin/"tavern"
  end

  test do
    assert_equal "tavern #{version}", shell_output("#{bin}/tavern --version").strip
  end
end
`
}

if (import.meta.main) {
  const [command, arg] = process.argv.slice(2)
  if (command === "compile") compile()
  else if (command === "brew" && arg) process.stdout.write(brew(arg))
  else {
    console.error("usage: bun release/targets.ts compile | brew <tag>")
    process.exit(2)
  }
}
